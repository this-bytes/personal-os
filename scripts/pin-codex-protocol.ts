/** How big the generated bundle is, so the record can say what the subset is a subset of. */
function measureBundle(dir: string): { files: number; bytes: number } {
  let files = 0;
  let bytes = 0;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const child = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      const nested = measureBundle(child);
      files += nested.files;
      bytes += nested.bytes;
      continue;
    }
    files += 1;
    bytes += fs.statSync(child).size;
  }
  return { files, bytes };
}

/**
 * The method table, with the methods this route does not use taken out.
 *
 * Each entry of the table's `oneOf` is one method, named by its `method`
 * enum. The entries that are kept are the generated bytes, unchanged.
 */
function trimMethods(raw: string, keep: string[]): { text: string; kept: number } {
  const root = scanObject(raw, 0);
  const array = root.find((member) => member.key === 'oneOf');
  if (!array) return { text: raw, kept: 0 };

  const elements = scanArray(raw, array.valueStart);
  const kept: Array<{ valueStart: number; valueEnd: number }> = [];
  for (const element of elements) {
    const name = methodNameOf(raw.slice(element.valueStart, element.valueEnd));
    if (name && keep.includes(name)) kept.push(element);
  }
  if (kept.length === elements.length) return { text: raw, kept: kept.length };

  const openBracket = array.valueStart;
  const closeBracket = array.valueEnd - 1;
  const first = elements[0];
  const last = elements[elements.length - 1];
  const indent = first ? raw.slice(openBracket + 1, first.valueStart) : '';
  const closing = last ? raw.slice(last.valueEnd, closeBracket) : '';

  const elementText = kept
    .map((element) => `${indent}${raw.slice(element.valueStart, element.valueEnd)}`)
    .join(',');

  const rebuilt = `${raw.slice(0, openBracket)}[${elementText}${closing}${raw.slice(closeBracket)}`;
  return { text: rebuilt, kept: kept.length };
}

/** The method an entry of the table names, when it names one. */
function methodNameOf(entry: string): string | undefined {
  const match = /"method"\s*:\s*\{[^{}]*?"enum"\s*:\s*\[\s*"([^"]+)"/s.exec(entry);
  return match?.[1];
}

/** The elements of the JSON array that starts at `start`, and where they sit. */
function scanArray(text: string, start: number): Array<{ valueStart: number; valueEnd: number }> {
  let i = start + 1;
  const elements: Array<{ valueStart: number; valueEnd: number }> = [];

  for (;;) {
    i = skipWhitespace(text, i);
    if (text[i] === ']') return elements;
    const valueStart = i;
    const valueEnd = scanValue(text, i);
    elements.push({ valueStart, valueEnd });
    i = skipWhitespace(text, valueEnd);
    if (text[i] === ',') {
      i += 1;
      continue;
    }
    if (text[i] === ']') return elements;
    throw new Error(`Expected a comma or a closing bracket at offset ${i}.`);
  }
}

/**
 * The file, with the definitions nothing reaches taken out.
 *
 * The work is done on the raw text, so what stays is the generated bytes.
 */
function trimToReachableDefinitions(raw: string): { text: string; kept: number } {
  const root = scanObject(raw, 0);
  const definitions = root.find((member) => member.key === 'definitions');
  if (!definitions) {
    // A file without definitions is already as small as it gets.
    return { text: raw, kept: 0 };
  }

  const members = scanObject(raw, definitions.valueStart);
  const byKey = new Map(members.map((member) => [member.key, member]));

  // The definitions the rest of the file reaches, and the ones those reach.
  // The generated bundle puts `definitions` before `properties`, so the roots
  // are the references that come after it.
  const reachable = new Set<string>();
  const queue: string[] = [];
  for (const name of collectRefs(raw.slice(definitions.valueEnd))) queue.push(name);
  while (queue.length > 0) {
    const name = queue.pop() as string;
    if (reachable.has(name)) continue;
    reachable.add(name);
    const member = byKey.get(name);
    if (!member) continue;
    for (const next of collectRefs(raw.slice(member.valueStart, member.valueEnd))) queue.push(next);
  }

  const kept = members.filter((member) => reachable.has(member.key));
  if (kept.length === members.length) {
    return { text: raw, kept: kept.length };
  }

  // The whitespace the generated file used, so what stays keeps the
  // indentation it was generated with.
  const openBrace = definitions.valueStart;
  const closeBrace = definitions.valueEnd - 1;
  const first = members[0];
  const last = members[members.length - 1];
  const indent = first ? raw.slice(openBrace + 1, first.keyStart) : '';
  const closing = last ? raw.slice(last.valueEnd, closeBrace) : '';

  const memberText = kept
    .map((member) => `${indent}${raw.slice(member.keyStart, member.valueEnd)}`)
    .join(',');

  const rebuilt = `${raw.slice(0, openBrace)}{${memberText}${closing}${raw.slice(closeBrace)}`;

  return { text: rebuilt, kept: kept.length };
}

/** A member of a JSON object, and where it sits in the text. */
interface Member {
  key: string;
  keyStart: number;
  valueStart: number;
  valueEnd: number;
}

/**
 * The members of the JSON object that starts at `start`.
 *
 * The offsets are what make the trimming verbatim: the text of a member is
 * copied, not rebuilt.
 */
function scanObject(text: string, start: number): Member[] {
  let i = start + 1;
  const members: Member[] = [];

  for (;;) {
    i = skipWhitespace(text, i);
    if (text[i] === '}') return members;
    if (text[i] !== '"') throw new Error(`Expected a key at offset ${i}.`);

    const keyStart = i;
    const keyEnd = scanString(text, i);
    const key = JSON.parse(text.slice(keyStart, keyEnd)) as string;

    i = skipWhitespace(text, keyEnd);
    if (text[i] !== ':') throw new Error(`Expected a colon at offset ${i}.`);
    i = skipWhitespace(text, i + 1);

    const valueStart = i;
    const valueEnd = scanValue(text, i);
    members.push({ key, keyStart, valueStart, valueEnd });

    i = skipWhitespace(text, valueEnd);
    if (text[i] === ',') {
      i += 1;
      continue;
    }
    if (text[i] === '}') return members;
    throw new Error(`Expected a comma or a closing brace at offset ${i}.`);
  }
}

/** The offset after the string that starts at `start`. */
function scanString(text: string, start: number): number {
  let i = start + 1;
  while (i < text.length) {
    if (text[i] === '\\') {
      i += 2;
      continue;
    }
    if (text[i] === '"') return i + 1;
    i += 1;
  }
  throw new Error('A string that never ends.');
}

/** The offset after the value that starts at `start`. */
function scanValue(text: string, start: number): number {
  const first = text[start];
  if (first === '"') return scanString(text, start);
  if (first === '{' || first === '[') {
    const close = first === '{' ? '}' : ']';
    let depth = 0;
    let i = start;
    while (i < text.length) {
      const char = text[i];
      if (char === '"') {
        i = scanString(text, i);
        continue;
      }
      if (char === '{' || char === '[') depth += 1;
      if (char === '}' || char === ']') {
        depth -= 1;
        if (depth === 0) {
          if (char !== close) throw new Error(`Mismatched bracket at offset ${i}.`);
          return i + 1;
        }
      }
      i += 1;
    }
    throw new Error('A value that never ends.');
  }

  // A number, a boolean or null.
  let i = start;
  for (;;) {
    const char = text[i];
    if (char === undefined || ',}] \t\r\n'.includes(char)) break;
    i += 1;
  }
  return i;
}

/** The offset of the next character that is not whitespace. */
function skipWhitespace(text: string, start: number): number {
  let i = start;
  for (;;) {
    const char = text[i];
    if (char === undefined || !/\s/.test(char)) break;
    i += 1;
  }
  return i;
}

/** The definitions the text reaches. */
function collectRefs(text: string): string[] {
  const names: string[] = [];
  const pattern = /"\$ref"\s*:\s*"#\/definitions\/([^"]+)"/g;
  let match = pattern.exec(text);
  while (match) {
    names.push(match[1] as string);
    match = pattern.exec(text);
  }
  return names;
}
