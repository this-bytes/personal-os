/**
 * Pin the App Server protocol this repository's adapter is written against.
 *
 * The App Server publishes its own JSON Schema, and the schema changes with the
 * runtime. A protocol the repository depends on and does not pin is a protocol
 * that can change under it, so the schema the adapter was written against is
 * committed beside the adapter.
 *
 * **The committed schema is a subset, and it says so.** The whole bundle is
 * about 730 KB of generated JSON, and most of it is not the route this
 * repository implements. What is committed is the schema of the methods and
 * notifications the adapter actually uses, and — for each of those — the
 * definitions it depends on. Nothing is paraphrased: every definition is the
 * generated bytes, unchanged, and only the definitions nothing reaches are
 * dropped.
 *
 *   codex app-server generate-json-schema --out <DIR>
 *   npx tsx scripts/pin-codex-protocol.ts --from <DIR> --version 0.163.0
 *
 * The generation command and the runtime's version are recorded in `PINNED.md`
 * beside the schema.
 */
